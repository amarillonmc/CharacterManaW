export function detectLanguage() {
  const saved = localStorage.getItem('cnw:language');
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.languages?.[0] || navigator.language || 'ja').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('en')) return 'en';
  return 'ja';
}

export function t(lang, key, vars = {}) {
  const dict = I18N[lang] || I18N.ja;
  let value = key.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), dict);
  if (value === undefined) value = key.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), I18N.ja);
  if (Array.isArray(value)) return value;
  if (typeof value !== 'string') return String(value ?? key);
  return value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function applyI18n(root, lang) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.getAttribute('data-i18n');
    const value = t(lang, key);
    if (typeof value === 'string') el.textContent = value;
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.setAttribute('placeholder', t(lang, el.getAttribute('data-i18n-placeholder')));
  }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
}
